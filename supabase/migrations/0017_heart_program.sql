--   "ХҮРЭН ЗҮРХ" үндэсний хөтөлбөр — хүрэн манжингийн бүтээгдэхүүн
--   худалдан авахад ширхэг тутмаас 30₮ "Зүрх мартахгүй" төсөлд
--   хандивлагдана. Тухайн бүтээгдэхүүний хуудсанд мэдэгдэл харагдана.
--
--   Зөвхөн НЭМЭЛТ багана — default false тул одоо байгаа бараанд
--   нөлөөлөхгүй. Админ хэсгээс бараа бүрээр асаах/унтраах боломжтой.
-- ============================================================

alter table public.products
  add column if not exists heart_program boolean not null default false;

comment on column public.products.heart_program is
  'ХҮРЭН ЗҮРХ хөтөлбөрт хамрагдах эсэх — бүтээгдэхүүний хуудсанд хандивын мэдэгдэл харуулна';

-- Хөтөлбөрт хамрагдах хүрэн манжингийн бүтээгдэхүүнүүд
update public.products
set heart_program = true
where slug in (
  'huren-manjin-shuus-250ml',        -- Хүрэн манжин Шүүс 270мл
  'huren-manjin-alim-smuuti-250ml',  -- Хүрэн манжин, Алим Смүүти 270мл
  'huren-manjin-alim-nuhash-180g',   -- Хүрэн манжин, Алим нухаш 180г
  'huren-manjin-alim-nuhash-720g',   -- Хүрэн манжин, Алим нухаш 720г
  'huren-manjin-salat-520g'          -- Хүрэн манжин салат 550г
);
