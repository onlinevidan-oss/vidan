-- 0035_ga_client_id.sql
--   ХӨРВӨЛТИЙГ СЕРВЕР ТАЛААС ХЭМЖИХ
--
--   АСУУДАЛ: GA4-ийн `purchase` эвент зөвхөн /checkout/success хуудас
--   ачаалагдвал бичигддэг. Трафикийн 90% нь гар утас — банкны апп руу
--   үсэрч төлөөд браузерт буцаж ирэхгүй хүн огт тоологдоогүй.
--   Хэмжилт: GA4 дээр 4 худалдан авалт, өгөгдлийн санд 11.
--
--   ШИЙДЭЛ: захиалга үүсэх мөчид GA-гийн client_id-г (_ga күүки)
--   хадгална. Төлбөр баталгаажмагц сервер талаас Measurement Protocol-оор
--   `purchase` илгээнэ — браузер нээлттэй эсэхээс үл хамаарна.
--
--   Түүхий client_id нь GA-гийн түр зуурын танигч. Хувь хүнийг
--   тодорхойлдоггүй, зөвхөн тухайн browser-ийн session-тэй холбогдоно.
-- ============================================================

alter table public.orders
  add column if not exists ga_client_id text;

comment on column public.orders.ga_client_id is
  'GA4 client_id (_ga күүкиэс). Серверээс purchase эвент илгээхэд хэрэгтэй.';
