--   ИЛРҮҮЛСЭН АЛДАА (2026-10-05): #10314 захиалгад `ebarimt_created`
--   бичлэг ХОЁР УДАА, 239 миллисекундын зөрүүтэй орсон байв. Улмаар
--   сугалааны дугаарын SMS захиалагч руу хоёр удаа явсан.
--
--   Шалтгаан нь 0024-д зассантай ижил race: QPay-ийн callback болон
--   хэрэглэгчийн браузерын polling хоёулаа `verifyAndMarkPaid`-г зэрэг
--   дуудахад, хоёулаа `ebarimt_id` хоосныг уншаад хоёулаа үргэлжилсэн.
--   Кодын `if (order.ebarimt_id) return` хамгаалалт нь зэрэг уншихад
--   ажиллахгүй.
--
--   Шийдэл: ажил эхлэхийн ӨМНӨ order_events-д тэмдэглэгээ бичнэ.
--   Энэ индекс хоёр дахь бичилтийг DB түвшинд таслана.
--
--   0024-ийн индексийг ХӨНДӨХГҮЙ — тусдаа хэсэгчилсэн индекс нэмнэ.
--   Ингэснээр order_events дээр ACCESS EXCLUSIVE lock авахгүй.
--
--   ⚠️ `ebarimt_claim` нь АЛДАА ГАРВАЛ УСТГАГДАНА (код талд) — эс
--   тэгвэл QPay түр унасан тохиолдолд захиалга үүрд баримтгүй үлдэнэ.
--   `sms_lottery` харин устгагддаггүй: давхар мессеж илгээснээс нэг
--   мессеж алдсан нь дээр.
-- ============================================================

create unique index if not exists order_events_ebarimt_once_idx
  on public.order_events (order_id, event_type)
  where event_type in ('ebarimt_claim', 'sms_lottery');
