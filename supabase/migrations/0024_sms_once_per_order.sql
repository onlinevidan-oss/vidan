-- ============================================================
-- 0024_sms_once_per_order.sql
--   Нэг захиалгад ижил төрлийн SMS ЗӨВХӨН НЭГ УДАА явна.
--
--   ИЛРҮҮЛСЭН АЛДАА: 2026-08-15-ны захиалгад "paid" SMS 2 секундын
--   зөрүүтэй ХОЁР УДАА явсан. Шалтгаан: QPay-ийн callback болон
--   client талын polling хоёулаа verifyAndMarkPaid()-г зэрэг дуудахад
--   хоёулаа "төлөгдөөгүй" төлвийг уншаад хоёулаа SMS илгээсэн (race).
--   Кодын `if (inv.status === 'paid') return` хамгаалалт нь хоёр
--   процесс ЗЭРЭГ уншихад ажиллахгүй.
--
--   Шийдэл: SMS илгээхийн ӨМНӨ order_events-д тэмдэглэгээ бичнэ.
--   Энэ unique index нь хоёр дахь бичилтийг DB түвшинд таслана —
--   давхар SMS илгээгдэхгүй (мөнгө, хэрэглэгчийн тэвчээр хэмнэнэ).
--
--   Хуучин 'sms_sent' бичлэгүүд энэ индекст хамрагдахгүй (давхардсан
--   мөр байгаа тул) — зөвхөн шинэ төрлүүдэд үйлчилнэ.
-- ============================================================

create unique index if not exists order_events_sms_once_idx
  on public.order_events (order_id, event_type)
  where event_type in ('sms_paid', 'sms_cancelled');
