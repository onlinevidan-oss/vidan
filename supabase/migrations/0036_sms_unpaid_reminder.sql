--   ТӨЛӨӨГҮЙ ЗАХИАЛГЫН САНУУЛГА SMS — нэг удаа
--
--   ХЭМЖИЛТ (2026-09-16): QR хуудсанд хүрсэн 38 захиалга төлөгдөөгүй,
--   нийт 3,171,364₮. Эдгээрийн ХЭН НЭГЭНД Ч сануулга явуулаагүй.
--   Бүгд SMS кодоор нэвтэрсэн тул утасны дугаар нь бидэнд байгаа.
--
--   0024-ийн индекс зөвхөн 'sms_paid', 'sms_cancelled'-ыг хамарсан.
--   Түүнийг ХӨНДӨХГҮЙ — 'sms_unpaid'-д зориулж тусдаа хэсэгчилсэн
--   индекс нэмнэ. Ингэснээр байгаа индексийг drop хийхгүй тул
--   order_events дээр ACCESS EXCLUSIVE lock авах шаардлагагүй.
--
--   Зорилго нэг: нэг захиалгад сануулга ХОЁР УДАА явахгүй байх.
--   Давтсан мессеж мөнгө үрэхээс гадна хэрэглэгчийг залхаана.
-- ============================================================

create unique index if not exists order_events_sms_unpaid_once_idx
  on public.order_events (order_id, event_type)
  where event_type = 'sms_unpaid';
